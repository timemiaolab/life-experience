function build(): AppData {
  const nodes: GNode[] = [...AREAS.map((n) => ({ ...n, demo: true }))];
  const links: Link[] = [];
  const contributions: Contribution[] = [];
  let sIdx = 0;
  CONTRIBUTIONS.forEach((c, ci) => {
    const cid = `c${String(ci + 1).padStart(2, '0')}`;
    const createdAt = `${D}${String(c.day).padStart(2, '0')}`;
    const sceneIds: string[] = [];
    c.scenes.forEach((s) => {
      sIdx++;
      const sid = `s${sIdx}`;
      sceneIds.push(sid);
      nodes.push({ id: sid, layer: 'scene', title: s.title, desc: s.desc, tag: s.tag, contributionId: cid, createdAt, demo: true });
      links.push([s.area, sid]);
      s.ps.forEach((p) => links.push([sid, p]));
    });
    contributions.push({ id: cid, identity: c.identity, story: c.story, createdAt, sceneIds, demo: true, engine: 'seed' });
  });
  PRINCIPLES.forEach(({ ideas, ...p }) => {
    nodes.push({ ...p, demo: true, createdAt: `${D}25` });
    ideas.forEach((i) => links.push([p.id, i]));
  });
  IDEAS.forEach((n) => nodes.push({ ...n, demo: true, createdAt: `${D}28` }));
  MEANINGS.forEach((n) => nodes.push({ ...n, demo: true, createdAt: `${D}30` }));
  links.push(...IDEA_TO_MEANING);
  // 「有用」票从 0 开始：不伪造任何社区统计
  return { version: SEED_VERSION, contributions, nodes, links, votes: {}, myVotes: [] };
}

export const SEED: AppData = build();
export const seedClone = (): AppData => JSON.parse(JSON.stringify(SEED));

